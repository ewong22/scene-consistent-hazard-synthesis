import numpy as np
import torch
from torch.utils.data import Dataset
from pathlib import Path
from PIL import Image
import cv2

# Configuration
# This must match the OUTPUT_DIR from your main_pipeline.py
SYNTHETIC_ROOT = Path("data/synthetic_model_c")

class SyntheticInstanceDataset(Dataset):
    """
    Loads the synthetic images and masks generated by the Model C pipeline.
    """
    def __init__(self, transform=None):
        self.transform = transform
        self.img_dir = SYNTHETIC_ROOT / "images"
        self.mask_dir = SYNTHETIC_ROOT / "masks"
        
        # List all generated png images
        self.images = list(self.img_dir.glob("*.png"))
        
        if len(self.images) == 0:
            print(f"[WARN] No synthetic data found in {self.img_dir}. Did you run main_pipeline.py?")

    def __len__(self):
        return len(self.images)

    def __getitem__(self, idx):
        img_path = self.images[idx]
        
        # Construct mask path based on naming convention in main_pipeline
        # Image: Name_var1.png -> Mask: Name_var1_gtCoarse_labelIds.png
        mask_filename = img_path.name.replace(".png", "_gtCoarse_labelIds.png")
        mask_path = self.mask_dir / mask_filename

        # 1. Load Image
        # Convert to float tensor (0.0 to 1.0)
        img = Image.open(img_path).convert("RGB")
        img_np = np.array(img, dtype=np.float32) / 255.0
        img_tensor = torch.from_numpy(img_np).permute(2, 0, 1)

        # 2. Load Label
        # This mask has ID 2 for hazards (as defined in our pipeline)
        if not mask_path.exists():
            # Fallback if mask is missing (should not happen if pipeline finished)
            print(f"Warning: Mask not found for {img_path.name}")
            label_raw = np.zeros((img_np.shape[0], img_np.shape[1]), dtype=np.uint8)
        else:
            label_raw = np.array(Image.open(mask_path), dtype=np.uint8)
        
        # 3. Process Instances for Mask R-CNN
        # We look for pixels with value 2 (Hazard)
        hazard_mask = (label_raw == 2).astype(np.uint8)

        # Find individual objects (contours) in the mask
        contours, _ = cv2.findContours(hazard_mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)

        boxes = []
        masks = []
        labels = []

        for contour in contours:
            # Filter extremely small noise (optional)
            if cv2.contourArea(contour) < 50:
                continue

            # Create binary mask for this specific object
            mask = np.zeros_like(hazard_mask)
            cv2.drawContours(mask, [contour], -1, 1, thickness=-1)
            
            # Get bounding box
            x, y, w, h = cv2.boundingRect(contour)
            
            # Mask R-CNN expects: [x_min, y_min, x_max, y_max]
            boxes.append([x, y, x+w, y+h])
            masks.append(mask)
            labels.append(1) # Class 1 = Hazard

        # Format as Torch Tensors
        if len(boxes) == 0:
            # Handle empty images (no hazards found)
            target = {
                "boxes": torch.zeros((0, 4), dtype=torch.float32),
                "labels": torch.zeros((0,), dtype=torch.int64),
                "masks": torch.zeros((0, label_raw.shape[0], label_raw.shape[1]), dtype=torch.uint8),
                "image_id": torch.tensor([idx])
            }
        else:
            target = {
                "boxes": torch.as_tensor(boxes, dtype=torch.float32),
                "labels": torch.as_tensor(labels, dtype=torch.int64),
                "masks": torch.as_tensor(np.array(masks), dtype=torch.uint8),
                "image_id": torch.tensor([idx])
            }

        return img_tensor, target